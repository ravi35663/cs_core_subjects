/*
=>  What are design Patters:
    -   Design patterns are proven solution to recurring design problems in development.
    -   They are not code, rather best practices shaped into reusable abstractions.

=>  Types of Design patterns: (GoF): (Gang of Four) (23)
    -   Creational (5)
    -   Structural (7)
    -   Behavioral (11)
*/

/*
=>  Creational Pattern:
    -   Creational patterns deal with object creation mechanism.

=>  Type of Creational Pattern:
    1) Singleton
    2) Factory
    3) Abstract
    4) Builder
    5) Prototype
*/
/*
=>  Structural Pattern:
    -   Structural patterns focuses on how classes and objects are composed to form 
        larger structure.
    -   It helps system to work together that otherwise could not because of 
        incompatible interfaces
    -   Structural patterns are about how classes and objects are connected to form 
        larger, flexible structures. They focus on composition (has-a) rather than 
        inheritance.

=>  Types of Structural Patterns:
    1) Adaptor
    2) Bridge
    3) Composition
    4) Decorator
    5) Facade
    6) Flyweight
    7) Proxy
*/
/*
=>  Behavioral Pattern:
    -   This is very important patterns you should remember
    -   concerned with communication between objects.

=> Type of Behavioral Pattern:
    1) Chain of responsibility
    2) Strategy 
    3) Command
    4) Observer
    5) Mediator
    6) State
    7) Template Method
    8) Visitor
    9) Iterator
    10) Memento
    11) Interpreter
*/