/*
=> Mediator Design Pattern:
    -   It is behavioral design pattern that centralizes complex communication between objects into a 
        mediator object.
    -   It promotes loose coupling and organizes the interaction between components.
*/

/*
=> When to use mediator pattern:
    -   Multiple users or services interact but should remain decouples
    -   You want to manage rules or permissions centrally
    -   You need flexible broadcasting, filtering or transformation of messages
*/