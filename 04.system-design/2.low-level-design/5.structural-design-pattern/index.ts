/*
=> Structural Design Pattern:
    -   Structural Design Patterns are patterns that focus on how classes and 
        objects are composed to form larger structures — while keeping them 
        flexible and efficient.

    -   They help you connect objects/classes in a smart way
    -   Without making your system tightly coupled
*/
/*
=> Note:
    - Creational  -->  How objects are created
    - Structural  -->  How objects are connected
    - Behavioral  -->  How objects communicate
*/
/*
=> Why Do We Need Structural Patterns:
    ->  Without them, code becomes:
        - Tightly coupled
        - Hard to change
        - Hard to extend
        - Difficult to test

    ->  With them:
        - Flexible
        - Reusable
        - Maintainable
        - Scalable
*/