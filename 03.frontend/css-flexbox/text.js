/*
=>  Pre-flexbox:
    -   Use different positional properties, such as 'absolute'
    -   Floats and clear fixes
    -   Fixed heights for columns 
*/

/*
=>  Enter flex box:
    -   Flex box is CSS display type designed to help us craft CSS layouts much 
        easier.
    -   Control the position, size and spacing of elements relative to their parent 
        element and each other.
    -   Works great responsively.
    -   Flex box apply a display type of flex to the parent container
*/

/*
=>  Benefits of using flex box:
    -   Navigation bars & menus
    -   Grid layouts
    -   Bar chart
    -   Equal height column
*/
 