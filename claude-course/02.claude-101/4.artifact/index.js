/*
==================== CLAUDE ARTIFACTS ====================
    - Artifacts = Outputs you create with Claude that are meant to be edited, reused, or shared.

    - Examples:
        - Documents
        - Presentations/decks
        - Designs
        - Dashboards
        - Prototypes
        - Interactive pages
        - Working code

    - Instead of having a long output buried in chat, the artifact appears in a separate workspace where 
      you can continue editing it.

    - If needed, explicitly say: "Create this as an artifact."

----------------------------------------------------------
1. WHERE ARTIFACTS LIVE
----------------------------------------------------------
=>  On paid plans:
        - Artifacts are saved in the Artifacts tab.
        - They are not tied only to the conversation that created them.
        - You can reopen, edit, and share them later.

Think:
    Conversation → Create the artifact
    Artifacts tab → Store and continue working on it

On Free:
    - The artifact stays with the conversation that created it.

----------------------------------------------------------
2. MAIN TYPES OF ARTIFACTS
----------------------------------------------------------
    - Claude provides specialized experiences for common deliverables:

    1) DESIGN
        - Landing pages
        - One-pagers
        - Product mockups
        - UI prototypes

        - Example:
            "Design a landing page for a productivity app."

    2) SLIDES
        - Creates presentations from notes, reports, or conversations.
        - Claude can outline, write, and design the slides.
        - Slides can be edited and exported to PPTX/PDF.

        - Example:
            "Turn these meeting notes into a 5-slide presentation."

    3) DOCS
        - Living documents that you and Claude can edit together.
        - Supports rich text, comments, charts, and diagrams.
        - Can be exported to Google Docs or DOCX.

        - Example:
            "Create a one-page project brief for the onboarding project."

    - These can also work together:
        Document → "Turn this into a deck."
        Deck     → "Create a one-pager from this."

----------------------------------------------------------
3. ARTIFACTS ON EVERY PLAN
----------------------------------------------------------
- Not every artifact needs Design, Slides, or Docs.

=>  Claude can also create artifacts such as:
    - Dashboards
    - Trackers
    - Flowcharts
    - Interactive pages
    - Working code

    - Example:
        "Build an interactive dashboard where I enter monthly expenses and see a category breakdown."

    - These can be created as artifacts on every plan, including Free.

    - IMPORTANT:
        Artifacts ≠ File creation

        Artifact:
            → Opens and updates inside Claude
            → Can be shared by link

        File creation:
            → Produces downloadable files
            → Example: .docx, .xlsx, .pptx, .pdf

----------------------------------------------------------
4. CREATING AN ARTIFACT
----------------------------------------------------------
Simply describe the deliverable you want.

Examples:
    "Turn these meeting notes into a 5-slide deck."
    "Create a project brief as a shareable document."
    "Design a landing page for a productivity app."
    "Build an interactive expense dashboard."

=>  Claude uses the context it already has:
    - Conversation
    - Uploaded files
    - Project knowledge
    - Connected tools

So you don't need to repeat all the context.

----------------------------------------------------------
5. HOW TO EDIT AN ARTIFACT
----------------------------------------------------------
There are 3 main ways:

1) EDIT DIRECTLY
   Make changes yourself.
   Example:
       Fix a typo or move/resize a design element.

2) COMMENT
   Tell Claude exactly what needs changing.

   Example:
       "Change this heading to make it more concise."

3) ASK IN THE CONVERSATION
   Continue talking to Claude and ask for another version.

   Example:
       "Make the presentation more suitable for executives."

    You can mix all three approaches.

----------------------------------------------------------
6. SHARING ARTIFACTS
----------------------------------------------------------
    -   Artifacts are private by default.
    -   Depending on your plan, you can give others permission to:
        - View
        - Comment
        - Edit
    -   Example:
        - Designer → Edit
        - Manager  → Comment
        - Client   → View

    -   Sharing options depend on the Claude plan and organization settings.
    -   The important idea:
            - You control who can access and modify the artifact.

----------------------------------------------------------
7. EXPORTING ARTIFACTS
----------------------------------------------------------
    -   When the work needs to leave Claude, export it.
    -   Examples:
            Deck    → .pptx / .pdf
            Design  → .pptx / .pdf / .html
            Doc     → Google Docs / .docx

    -   You can also copy or download artifacts directly.

----------------------------------------------------------
8. BEST PRACTICES
----------------------------------------------------------
1) ASK FOR THE DELIVERABLE, NOT JUST THE CONTENT
    Bad:
        "Summarize our Q3 results."
    Better:
        "Create a one-page Q3 results document for leadership."
    The second clearly tells Claude what final output you need.

2) BE SPECIFIC:
    Instead of:
        "Build a budget tracker."
    Say:
        "Build a monthly budget tracker where I can enter expenses by category, see a chart, and get a 
        warning when I exceed my budget."

3) DESCRIBE THE END USER
    Example:
        "Create a flowchart for new employees."
        is different from:
        "Create a flowchart for the engineering team."

    Knowing the audience helps Claude make better design choices.

4. BUILD ON EXISTING WORK:
    -   Artifacts are especially useful after you have already discussed a topic with Claude.

    Example:
        Research → Analysis → Discussion → Create final deck
        Claude already has the context from the conversation.

5. REFRESH DATA WHEN NEEDED
    -   Charts and diagrams created from connected data are not automatically live.
    -   If you need current data, ask Claude to refresh the data and update the artifact.

----------------------------------------------------------
KEY IDEA
----------------------------------------------------------
Artifact = A usable output that you can EDIT, REUSE, and SHARE.
    Instead of:
        Claude → Long text in chat
    You can have:
        Claude
        ↓
        Artifact
        ├── Edit
        ├── Comment
        ├── Refine
        ├── Share
        └── Export

Best approach:
    Understand the task
         ↓
    Ask for the actual deliverable
         ↓
    Create artifact
         ↓
    Review + edit
         ↓
    Share / export

    Artifacts are especially useful for deliverables that you will continue working on instead of 
    reading only once.
*/