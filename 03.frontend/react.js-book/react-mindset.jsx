/*
=> Core React Thinking Principles (Short & Simple):

1. Think in Components:
   - Break the UI into small, reusable components.
   - Each component should do one job (single responsibility).
   - Build a component tree starting from the main App component.

2. Embrace Declarative Programming:
   - Describe what the UI should look like based on state.
   - Let React handle DOM updates automatically.
   - Focus on data and state, not manual DOM manipulation.

3. Understand State and Props:
   - State is data managed inside a component.
   - Props pass data from parent to child.
   - Lift state up only when multiple components need the same data.

4. Prefer Composition Over Inheritance:
   - Combine small components to build bigger ones.
   - Make components flexible using props.
   - Avoid tightly coupled components.

5. Follow Unidirectional Data Flow:
   - Data flows from parent to child.
   - Keep a single source of truth.
   - Lift state to a common parent when sharing is needed.

6. Get Comfortable with JSX:
   - JSX looks like HTML but runs as JavaScript.
   - Use {} to embed JavaScript expressions inside JSX.

7. Learn and Use Hooks:
   - useState manages component state.
   - useEffect handles side effects like API calls.
   - Hooks enable powerful logic in functional components.

8. Test and Debug Early:
   - Write unit tests for components.
   - Test different props and states.
   - Use tools like React DevTools for debugging.
*/
