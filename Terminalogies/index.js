/*
===> General Frontend Terminology:
    ->  HTML (HyperText Markup Language): The standard markup language used to structure web pages.
    ->  CSS (Cascading Style Sheets): A style sheet language used for describing the appearance of HTML elements 
        (colors, layout, fonts, etc.).
    ->  JavaScript (JS): A programming language that enables dynamic content, animations, and interactive 
        elements on web pages.
    ->  Framework: A pre-built collection of code and templates used to simplify development. Common frontend 
        frameworks include React, Vue.js, and Angular.
    ->  Responsive Design: A design approach that ensures a website works well on different screen sizes, from 
        mobile to desktop, often achieved using CSS techniques.
    ->  Media Query: A CSS feature used to apply different styles based on screen size, device orientation, 
        and resolution, helping achieve responsive design.
    ->  Component: Reusable, self-contained pieces of code that represent parts of the UI, such as buttons, 
        forms, or cards. Components are central to frameworks like React and Vue.
    ->  Single Page Application (SPA): A type of web application that loads a single HTML page and dynamically 
        updates content without reloading, enhancing speed and user experience.
    ->  Static Site: A website with fixed content that doesn’t change on the client side. Content remains the 
        same until the website is manually updated.
    ->  Bundler: A tool that compiles and packages multiple files into a single file for the browser. 
        Examples include Webpack, Parcel, and Vite.
*/

/*
===> UI Terminology:
    ->  UX (User Experience): The overall experience a user has with a product, encompassing ease of use, 
        accessibility, and satisfaction.
    ->  Wireframe: A basic, low-fidelity visual layout of a website or app that shows the structure of elements 
        without any design details.
    ->  Prototype: A high-fidelity interactive model that simulates how the final product will function, often 
        used for user testing.
    ->  Mockup: A static, high-fidelity design of a webpage or app, showing color, typography, and branding 
        without interactivity.
    ->  Grid System: A structure that allows elements to be aligned in a consistent manner using columns and 
        rows, providing layout consistency across a page.
    ->  Typography: The use of fonts, font sizes, line heights, and letter spacing to create visually appealing 
        text content in the UI.
    ->  Whitespace (Negative Space): The empty space around UI elements, which helps improve readability, 
        aesthetics, and user focus.
    ->  CTA (Call to Action): Interactive elements like buttons or links that prompt users to take a specific 
        action (e.g., "Sign Up" or "Learn More").
    ->  Modal: A dialog box or popup that appears on top of the main content to provide additional information 
        or prompt user action.
    ->  Navigation: The set of elements (e.g., menu, sidebar, breadcrumbs) that help users move through the 
        app or website.
    ->  Hero Section: The prominent, visually impactful section at the top of a webpage, often containing a 
        large image, headline, and CTA.
    ->  Card: A container component that displays information in a structured, often clickable format, 
        commonly used to showcase content snippets.
    ->  Loading Spinner: A UI element (like an animated circle) that indicates to users that content or data 
        is being loaded.
    ->  Toast Notification: A temporary message that appears on the screen to give feedback to users, often 
        for confirmations, alerts, or warnings.
    ->  Dropdown: A menu that reveals additional options when clicked, commonly used for selections like 
        filters or settings
*/

/*
===> Performance & Optimization Terminology:
    ->  Lazy Loading: A technique where images or content load only as the user scrolls to them, improving 
        initial load time.
    ->  Minification: The process of removing unnecessary characters (like whitespace) from code to reduce 
        file sizes and improve load times.
    ->  Caching: Storing data temporarily so that subsequent loads are faster.
    ->  Critical Rendering Path: The sequence of steps the browser takes to render a web page, from HTML and 
        CSS to the final rendered view.
    ->  DOM (Document Object Model): A structured representation of the HTML on a page. JavaScript interacts 
        with the DOM to manipulate elements and styles.
*/